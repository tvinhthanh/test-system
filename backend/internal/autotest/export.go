package autotest

import (
	"encoding/json"
	"fmt"
	"sort"
	"strconv"
	"strings"
)

// ExportCase is one case to write as a Playwright test.
type ExportCase struct {
	Title string
	Spec  Spec
}

// Playwright writes cases as one Playwright test file (QĐ-16) — what a team
// copies into its own repository to run the cases in its CI, reporting to
// ATP with the reporter. Generated from the steps, not by a model: every
// string is written as a JSON string, which is a valid JavaScript literal,
// and comments lose their line breaks, so no text in a step can become
// code. Passwords are never written: an account signs in with
// ATP_USER_<KEY> / ATP_PASS_<KEY> from the environment.
func Playwright(cases []ExportCase, accounts map[string]Account, baseURL, envKey string) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by ATP from %d runnable test case%s (environment %s).\n", len(cases), plural(len(cases)), comment(envKey))
	b.WriteString("// Run: ATP_BASE_URL=" + comment(baseURL) + " npx playwright test\n")
	b.WriteString("// With the ATP reporter in playwright.config.ts, the results land in ATP like any CI run.\n")
	b.WriteString(`import { test, expect, type Locator, type Page } from "@playwright/test";` + "\n\n")
	b.WriteString("const BASE_URL = process.env.ATP_BASE_URL ?? " + js(baseURL) + ";\n")
	b.WriteString(`const at = (path: string) => new URL(path, BASE_URL).href;
const containing = (s: string) => new RegExp(s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
const fresh = () => ({ random: Math.random().toString(36).slice(2, 8), timestamp: String(Math.floor(Date.now() / 1000)) });

// An exact name wins over one that only contains it, as when ATP runs the case.
async function pick(exact: Locator, loose: Locator): Promise<Locator> {
  await loose.first().waitFor({ state: "attached" }).catch(() => {});
  return (await exact.count()) > 0 ? exact.first() : loose.first();
}

function account(key: string) {
  const name = key.toUpperCase().replace(/-/g, "_");
  const username = process.env[` + "`ATP_USER_${name}`" + `];
  const password = process.env[` + "`ATP_PASS_${name}`" + `];
  if (!username || !password) throw new Error(` + "`Set ATP_USER_${name} and ATP_PASS_${name}`" + `);
  return { username, password };
}
`)
	used := map[string]bool{}
	for _, c := range cases {
		if c.Spec.Account != "" {
			used[c.Spec.Account] = true
		}
	}
	keys := make([]string, 0, len(used))
	for k := range used {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		a, ok := accounts[k]
		fmt.Fprintf(&b, "\nasync function signIn%s(page: Page) {\n", ident(k))
		fmt.Fprintf(&b, "  const v = { ...fresh(), ...account(%s) };\n", js(k))
		if !ok || len(a.LoginSteps) == 0 {
			fmt.Fprintf(&b, "  throw new Error(%s);\n}\n", js("ATP has no sign-in steps for the account "+k+" yet: run a case with it once, or write them"))
			continue
		}
		start := "/"
		if a.LoginURL != "" {
			start = a.LoginURL
		}
		fmt.Fprintf(&b, "  await page.goto(at(%s));\n", expr(start))
		for _, st := range a.LoginSteps {
			writeStep(&b, st, "  ")
		}
		b.WriteString("  await page.waitForLoadState(\"networkidle\").catch(() => {});\n}\n")
	}
	b.WriteString("\ntest.describe(\"ATP auto tests\", () => {\n")
	for _, c := range cases {
		fmt.Fprintf(&b, "  test(%s, async ({ page }) => {\n", js(c.Title))
		inputs := make([]string, 0, len(c.Spec.Inputs))
		for _, k := range sortedKeys(c.Spec.Inputs) {
			inputs = append(inputs, fmt.Sprintf("%s: %s", js(k), js(c.Spec.Inputs[k])))
		}
		if c.Spec.Account != "" {
			fmt.Fprintf(&b, "    await signIn%s(page);\n", ident(c.Spec.Account))
			fmt.Fprintf(&b, "    const v: Record<string, string> = { ...fresh(), ...account(%s), %s };\n", js(c.Spec.Account), strings.Join(inputs, ", "))
		} else {
			fmt.Fprintf(&b, "    const v: Record<string, string> = { ...fresh(), %s };\n", strings.Join(inputs, ", "))
		}
		fmt.Fprintf(&b, "    await page.goto(at(%s));\n", expr(c.Spec.Target))
		for _, st := range c.Spec.Steps {
			writeStep(&b, st, "    ")
		}
		b.WriteString("  });\n")
	}
	b.WriteString("});\n")
	return []byte(b.String())
}

func plural(n int) string {
	if n == 1 {
		return ""
	}
	return "s"
}

// js is s as a JavaScript string literal.
func js(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

// expr is text with {{variables}} as a JavaScript expression over v.
func expr(text string) string {
	var parts []string
	last := 0
	for _, m := range varRe.FindAllStringSubmatchIndex(text, -1) {
		if m[0] > last {
			parts = append(parts, js(text[last:m[0]]))
		}
		parts = append(parts, "v["+js(text[m[2]:m[3]])+"]")
		last = m[1]
	}
	if last < len(text) || len(parts) == 0 {
		parts = append(parts, js(text[last:]))
	}
	return strings.Join(parts, " + ")
}

// comment is text safe inside a // comment: no line breaks.
func comment(s string) string {
	return strings.NewReplacer("\r", " ", "\n", " ", " ", " ", " ", " ").Replace(s)
}

// ident is an account key as part of a function name (sign-in-default →
// SignInDefault).
func ident(key string) string {
	var b strings.Builder
	for _, part := range strings.Split(key, "-") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}

func locator(st Step, exact bool) string {
	name := expr(st.Name)
	ex := ""
	if exact {
		ex = ", exact: true"
	}
	switch st.By {
	case "role":
		if st.Name == "" {
			return fmt.Sprintf("page.getByRole(%s)", js(st.Role))
		}
		return fmt.Sprintf("page.getByRole(%s, { name: %s%s })", js(st.Role), name, ex)
	case "label":
		return fmt.Sprintf("page.getByLabel(%s%s)", name, map[bool]string{true: ", { exact: true }"}[exact])
	case "placeholder":
		return fmt.Sprintf("page.getByPlaceholder(%s%s)", name, map[bool]string{true: ", { exact: true }"}[exact])
	case "text":
		return fmt.Sprintf("page.getByText(%s%s)", name, map[bool]string{true: ", { exact: true }"}[exact])
	case "testid":
		return fmt.Sprintf("page.getByTestId(%s)", name)
	case "css":
		return fmt.Sprintf("page.locator(%s)", name)
	}
	return ""
}

// target is the step's element as an expression yielding a Locator.
func target(st Step) string {
	if st.By == "css" || st.By == "testid" || (st.By == "role" && st.Name == "") {
		return locator(st, false) + ".first()"
	}
	return fmt.Sprintf("(await pick(%s, %s))", locator(st, true), locator(st, false))
}

func writeStep(b *strings.Builder, st Step, indent string) {
	b.WriteString(indent + "// " + comment(sayOf(st)) + "\n")
	val := expr(st.Value)
	var line string
	switch st.Do {
	case "goto":
		line = fmt.Sprintf("await page.goto(at(%s));", val)
	case "click":
		line = fmt.Sprintf("await %s.click();", target(st))
	case "fill":
		line = fmt.Sprintf("await %s.fill(%s);", target(st), val)
	case "select":
		line = fmt.Sprintf("await %s.selectOption({ label: %s });", target(st), val)
	case "check":
		line = fmt.Sprintf("await %s.check();", target(st))
	case "uncheck":
		line = fmt.Sprintf("await %s.uncheck();", target(st))
	case "hover":
		line = fmt.Sprintf("await %s.hover();", target(st))
	case "press":
		if st.By == "" {
			line = fmt.Sprintf("await page.keyboard.press(%s);", val)
		} else {
			line = fmt.Sprintf("await %s.press(%s);", target(st), val)
		}
	case "wait":
		ms, _ := strconv.Atoi(st.Value)
		line = fmt.Sprintf("await page.waitForTimeout(%d);", ms)
	case "expect_visible":
		line = fmt.Sprintf("await expect(%s).toBeVisible();", target(st))
	case "expect_hidden":
		line = fmt.Sprintf("await expect(%s).toBeHidden();", target(st))
	case "expect_text":
		if st.By == "" {
			line = fmt.Sprintf("await expect(page.locator(\"body\")).toContainText(%s);", val)
		} else {
			line = fmt.Sprintf("await expect(%s).toContainText(%s);", target(st), val)
		}
	case "expect_url":
		line = fmt.Sprintf("await expect(page).toHaveURL(containing(%s));", val)
	case "expect_value":
		line = fmt.Sprintf("await expect(%s).toHaveValue(%s);", target(st), val)
	case "expect_title":
		line = fmt.Sprintf("await expect(page).toHaveTitle(containing(%s));", val)
	default:
		line = "// (unknown step skipped)"
	}
	b.WriteString(indent + line + "\n")
}
